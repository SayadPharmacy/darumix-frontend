/** Related articles sharing a tag, excluding the current one. */
export function relatedArticles(article, limit = 3) {
  if (!article) return articles.slice(0, limit);
  const sameTag = articles.filter(
    (item) => item.id !== article.id && item.tag === article.tag,
  );
  const others = articles.filter(
    (item) => item.id !== article.id && item.tag !== article.tag,
  );
  return [...sameTag, ...others].slice(0, limit);
}
